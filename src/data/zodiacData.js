export function getZodiacSign(month, day) {
  for (const sign of ZODIAC_SIGNS) {
    const [startM, startD] = sign.start;
    const [endM, endD] = sign.end;
    if (startM === endM) {
      if (month === startM && day >= startD && day <= endD) return sign;
    } else if (startM > endM) {
      // Wraps across the new year (e.g. Capricorn: Dec 22 - Jan 19)
      if ((month === startM && day >= startD) || (month === endM && day <= endD)) return sign;
    } else {
      if ((month === startM && day >= startD) || (month === endM && day <= endD)) return sign;
    }
  }
  return ZODIAC_SIGNS[0];
}